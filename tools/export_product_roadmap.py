#!/usr/bin/env python3
"""Export public bilingual roadmap notes from the page's single data source."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / 'docs' / 'product-roadmap'
PREFIX = 'window.PHOTOHOUSE_ROADMAP = '


def export() -> str:
    source = (PAGE / 'data.js').read_text(encoding='utf-8')
    data = json.loads(source.split(PREFIX, 1)[1].removesuffix('\n').removesuffix(';'))
    assert data['schema_version'] == 1
    ids = [f['id'] for f in data['features']]
    assert len(ids) == len(set(ids))
    def pair(value):
        assert set(value) == {'en', 'zh'} and all(isinstance(s, str) and s.strip() for s in value.values())
        return value['en'] + ' / ' + value['zh']
    lines = ['<!-- Generated by tools/export_product_roadmap.py; edit data.js instead. -->',
             '# PhotoHouse product roadmap / 产品路线图', '',
             pair(data['snapshot_label']), '', pair(data['runtime_notice']['title']), '',
             pair(data['runtime_notice']['body']), '',
             'This is a dated product record, not a live health check. / 这是有日期的产品记录，不是实时健康检查。', '',
             '## Priorities / 优先方向', '']
    for p in data['priorities']:
        lines += ['### ' + pair(p['title']), '', pair(p['why']), '',
                  '**Done when / 完成标准:** ' + pair(p['done_when']), '']
    stage = {'delivered': 'Recorded delivery / 已交付记录', 'source_ready': 'Source ready / 源码已就绪',
             'in_progress': 'In progress / 进行中', 'planned': 'Planned / 计划中'}
    priority = {'now': 'Now / 当前重点', 'next': 'Next / 下一步', 'later': 'Later / 后续'}
    lines += ['## Features / 功能', '']
    for f in data['features']:
        assert f['stage'] in stage and f['priority'] in priority
        assert f['area'] in [a['id'] for a in data['areas']]
        lines += ['<a id="' + f['id'] + '"></a>', '', '### ' + pair(f['title']), '',
                  stage[f['stage']] + ' · ' + priority[f['priority']], '', pair(f['summary']), '']
        for label, key in [('Implemented / 已实现', 'implementation'), ('Gaps / 差距', 'gaps')]:
            lines += ['**' + label + '**', ''] + ['- ' + pair(v) for v in f[key]] + ['']
        for label, key in [('Next / 下一步', 'next_step'), ('Delivery / 交付背景', 'delivery_note'),
                           ('Acceptance / 验收背景', 'acceptance_note')]:
            lines += ['**' + label + ':** ' + pair(f[key]), '']
        lines += ['**Evidence record / 证据记录**', '']
        lines += ['- ' + e['at'] + ' · ' + pair(e['label']) for e in f['evidence']]
        lines += ['']
    return '\n'.join(lines)


if __name__ == '__main__':
    (PAGE / 'roadmap.md').write_text(export(), encoding='utf-8')
